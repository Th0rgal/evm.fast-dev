#!/usr/bin/env python3
"""Port a pinned upstream spec into small InitECandidate Solver modules.

Usage: python3 campaign/notes/integration/split_spec.py --upstream 8a79d9f28
The upstream tree stays untouched. Existing merged wiring is preserved and
regenerated with merge_shard.py after the spec's field list changes.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'submission/InitECandidate/Solver/Wave8GuestInv'
NS = 'InitECandidate.Solver.Wave8GuestInv'
SOURCE = 'campaign/specs-proposed/GuestInv.lean'
FROZEN_REVISION = '8a79d9f28bdd7a3522f8a9a81a892d9ecaabdeff'


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', default='8a79d9f28')
    args = parser.parse_args()
    sha = git('rev-parse', args.upstream).decode().strip()
    if sha != FROZEN_REVISION:
        parser.error(f'Wave 8 specification is frozen at {FROZEN_REVISION}')
    raw = git('show', f'{sha}:{SOURCE}')
    source = raw.decode()
    lines = source.splitlines()

    def at(marker):
        return next(i for i, line in enumerate(lines) if line.startswith(marker))

    ns = at(f'namespace {NS}')
    start = at('/-! ## 1.')
    bridge = at('/-! ## 4.')
    memory = at('/-! ## 5.')
    b = at('/-! ## 6.')
    leaves = at('/-! ### Unguarded leaves:')
    contracts = at('/-! ## 7.')
    primitives = at('/-! #### Assembly (PROVED):')
    assembly = at('theorem assembly_main (P : Primitives)')
    instance = at('/-- The leaves discharge the primitives')
    budget = at('/-! ## 8.')
    target = at('/-- End-to-end target of the campaign')
    expressions = at('/-- Evaluation of an expression at a state')
    expression_end = at('theorem evalAt_const')
    entry_defs = at('/-- `main`-only entry guard:')
    entry_defs_end = at('theorem initialMemory_postDecls')
    examples = at('/-! ### Round-1 counterexamples, pinned')
    end = at(f'end {NS}')
    options = [x for x in lines[:ns] if x.startswith('set_option')]
    opens = []
    for line in lines[ns+1:start]:
        if line.startswith('open '):
            opens.append(line)

    outputs = {}

    def module(name, imports, body, description):
        # Proof factoring only: the statements and frozen definitions are unchanged.
        joined = '\n'.join(body)
        if name == 'EntryBridge':
            start = joined.index('theorem coveredSourceTicksConsumedBounded_of_terminatingMainOnP')
            proof = joined.index(':= by',start)+len(':= by')
            stop = joined.index('/-- Main bridge',proof)
            joined = joined[:proof]+'''
  intro input outcome events hgas _hsource _hcov stCtxt s_decls _hst hdecls
  have hmeta := B2PostDecls.evaluateDecls_meta sourceDeclarations
    { sourceInitialState input with structs := stCtxt } s_decls
    (fun a => Classical.propDecidable ((sourceInitialState input).memaddrs a)) hdecls
  have hcode : s_decls.code = originalRuntimeCode := by
    rw [hmeta.code]
    exact B2PostDecls.map_ext rfl
  exact terminating_main_run_bound hmain s_decls hcode
    (fun k callee => hentry input stCtxt s_decls k callee hgas hdecls)

'''+joined[stop:]
        body = joined.splitlines()
        outputs[name.replace('.', '/') + '.lean'] = '\n'.join([
            *(f'import {x}' for x in imports), '',
            f'/-! {description}\nPorted from {SOURCE} @ {sha}.\nGenerated by campaign/notes/integration/split_spec.py. -/',
            '', *options, '', f'namespace {NS}', '', *opens, '',
            *body, '', f'end {NS}', ''])

    # Separate cost definitions from both the placeholder leaves and guarded contracts.
    module('Defs', ['InitECandidate.Solver.PanTerminatingBounded'],
           lines[start:bridge], 'Guarded definitions and metadata combinators.')
    module('EntryDefs', [NS + '.Defs'], lines[entry_defs:entry_defs_end],
           'Covered main-entry guards, independent of the source-clock bridge proof.')
    module('EntryBridge', [NS + '.EntryDefs', NS + '.EntryRunBound'],
           [*lines[bridge:entry_defs], *lines[entry_defs_end:memory]],
           'Covered main-entry definitions and source-clock bridge.')
    module('MemoryViews', [NS + '.Defs'], lines[memory:b],
           'Memory views, world/frame guards and EVM potential definitions.')
    module('Bounds', [NS + '.MemoryViews'], lines[b:leaves], 'Generated, closed Nat cost definitions.')
    module('Expressions', [NS + '.Bounds'], lines[expressions:expression_end],
           'Expression evaluation abbreviation and comparison decomposition for leaf proofs.')
    module('LeafStatements', [NS + '.Expressions'], lines[leaves:contracts],
           'Unguarded leaf statements; unmerged leaves retain their upstream placeholders.')
    contract_boundaries = [contracts, *[at(marker) for marker in (
        '/-! ### Every guard reads', '/-! ### Relational callee contracts',
        '/-! ### Constructor return typing', '/-! ### Outcome triples',
        '/-! ### Evaluating the `run_frames`', '/-! ### The glue, proved',
        '/-! ### Concrete compositions', '/-! ### Guarded bound leaves',
        '/-! #### Composition obligations')]]
    gbody_starts = [i for i in range(contract_boundaries[-1], primitives)
                   if lines[i].startswith('/-- The body of ')]
    contract_boundaries += gbody_starts[4::4] + [primitives]
    previous = None
    for n, (lo, hi) in enumerate(zip(contract_boundaries, contract_boundaries[1:])):
        optional_glue = lo == at('/-! ### The glue, proved')
        name = 'FrameGlue' if optional_glue else f'ContractParts.C{n:02}'
        body = [line for i, line in enumerate(lines[lo:hi], lo)
                if not expressions <= i < expression_end]
        imports = [previous] if previous else [NS + '.LeafStatements', NS + '.EntryDefs']
        module(name, imports, body, 'Guarded contracts and proved glue, bounded compilation unit.')
        if not optional_glue:
            previous = NS + '.' + name
    outputs['Contracts.lean'] = f'import {previous}\n\n/-! Frozen revision-9 guarded contracts, split for bounded builds. -/\n'
    outputs['Spec.lean'] = (f'import {NS}.Contracts\nimport {NS}.FrameGlue\nimport {NS}.EntryBridge\n\n'
                           f'/-! Compatibility entry point for the split spec @ {sha}.\n'
                           'Definitions live in Defs, costs in Bounds, unguarded leaves in\n'
                           'LeafStatements, and guarded contracts in Contracts. -/\n')
    module('Primitives', [NS + '.Contracts'], lines[primitives:assembly], 'Primitive obligation interface.')
    module('Assembly', [NS + '.Primitives', NS + '.EntryBridge'],
           [*lines[assembly:instance], *lines[budget:target], *lines[examples:end]],
           'Proved conditional source-clock assembly; no primitive instance is assumed.')
    fields = re.findall(r'^  («[^»]+») : ', '\n'.join(lines[primitives:assembly]), re.M)
    if not (OUT/'PrimitivesProved.lean').exists() or not (ROOT/'campaign/notes/integration/SHARDS.json').exists():
        module('PrimitivesProved', [NS + '.Primitives'],
               ['theorem primitives : Primitives where', *(f'  {f} := {f}' for f in fields)],
               'Primitive instance. merge_shard.py replaces placeholders with checked leaf applications.')
    OUT.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (OUT/name).parent.mkdir(parents=True, exist_ok=True)
        (OUT/name).write_text(content)
    note = {'source': SOURCE, 'source_commit': sha, 'frozen_tag': 'wave8-spec-frozen-r9',
            'proof_adaptations': ['factor the guarded main run through abstract-state EntryRunBound; no statement or definition changes'],
            'source_sha256': hashlib.sha256(raw).hexdigest(),
            'namespace': NS, 'primitive_fields': len(fields),
            'outputs_sha256': {name: hashlib.sha256(value.encode()).hexdigest()
                               for name, value in outputs.items() if name != 'PrimitivesProved.lean'}}
    (ROOT/'campaign/notes/integration/PORT.json').write_text(json.dumps(note, indent=2, sort_keys=True)+'\n')
    print(f'Ported {sha}; {len(fields)} fields; wrote {len(outputs)} modules')


if __name__ == '__main__':
    main()
